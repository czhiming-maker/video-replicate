#!/usr/bin/env python3
"""Generate src/constants.ts + src/spawn_points.json for the Remotion scene."""
import json

manifest = json.load(open("work/manifest.json"))
meta = json.load(open("work/canopy_meta.json"))
girl_meta = json.load(open("work/girl_meta.json"))
spawn = json.load(open("work/canopy_spawn.json"))

with open("src/spawn_points.json", "w") as f:
    json.dump(spawn, f)

dens_pts = [(d["frame"], d["px"]) for d in json.load(open("work/motion.json"))["storm_density"]]
loss_pts = [(d["frame"], d["frac"]) for d in json.load(open("work/motion.json"))["canopy_loss"]]

ts = f"""// Auto-generated by work/gen_constants.py — do not edit by hand.
export const W = 720;
export const H = 1280;
export const FPS = 24;
export const DURATION = 122;
export const EXT = {manifest['EXT']};

// camera pan: piecewise-linear tx(frame), plate coords -> view shift
export const PAN_FR = {[0, 20, 40, 60, 80, 100, 121]};
export const PAN_TX = {[0, -50, -105, -159, -212, -272, -336]};

export const CANOPY = {{
  x: {manifest['canopy_bbox']['x']},
  y: {manifest['canopy_bbox']['y']},
  w: {manifest['canopy_bbox']['w']},
  h: {manifest['canopy_bbox']['h']},
}};

export const GIRL = {list(manifest['girl'])};

export const GSEQ = {{x: {girl_meta['gseq'][0]}, y: {girl_meta['gseq'][1]}, w: {girl_meta['gseq'][2]}, h: {girl_meta['gseq'][3]}}};

export const SPRITES_LEAF: {{file: string; w: number; h: number}}[] =
  {json.dumps([{'file': s['file'], 'w': s['w'], 'h': s['h']} for s in manifest['sprites_leaf']])};

export const SPRITES_BOKEH: {{file: string; w: number; h: number}}[] =
  {json.dumps([{'file': s['file'], 'w': s['w'], 'h': s['h']} for s in sorted(manifest['sprites_leaf'], key=lambda x: -x.get('strict', 0))[:8]])};

export const SPRITES_CLUSTER: {{file: string; w: number; h: number}}[] =
  {json.dumps([{'file': s['file'], 'w': s['w'], 'h': s['h']} for s in manifest['sprites_canopy']])};

// measured storm-zone leaf pixel density (source video)
export const DENS_FR = {[p[0] for p in dens_pts]};
export const DENS_PX = {[p[1] for p in dens_pts]};

// measured canopy remain fraction
export const LOSS_FR = {[p[0] for p in loss_pts]};
export const LOSS_FRAC = {[round(p[1], 4) for p in loss_pts]};

// wind (view coords, px/frame): measured p85 vx 8.21 (pan-corrected), vy 3.79
export const WIND = {{vx: 8.2, vy: 3.8}};
"""

with open("src/constants.ts", "w") as f:
    f.write(ts)
print("constants.ts written")
